#!/usr/bin/env python3
"""Generates kernel/src/drivers/media/i2c/mt9m113_regs.h from the register table of the downstream (CyanogenMod 3.4) MT9M113 driver.

Input: mt9m113_reg.c of drivers/media/video/msm (Code Aurora Forum, GPL-2.0), copied to out/refs/cm-cam/ (see STATUS.md, "Camera").
Only `preview_snapshot_mode_reg_tbl` is taken: the 480 entries are plain writes of 16-bit values to 16-bit registers (no read-modify-write,
no byte accesses); the two delays are kept (MCU boot mode, PLL lock). The last block of the downstream table is commented out there and applied
by the driver code, as it is in ours.

  python -I scripts/tools/gen-mt9m113-table.py
"""
import re

SRC = 'out/refs/cm-cam/mt9m113_reg.c'
OUT = 'kernel/src/drivers/media/i2c/mt9m113_regs.h'

lines = open(SRC, encoding='latin-1').read().splitlines()
start = next(i for i, l in enumerate(lines) if 'preview_snapshot_mode_reg_tbl[]' in l)
end = next(i for i, l in enumerate(lines) if i > start and l.strip().startswith('};'))
pat = re.compile(r'\s*\{\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*,\s*(WORD_LEN|BYTE_LEN)\s*,\s*(\d+)\s*\}\s*,?\s*(?://\s*(.*))?')
entries = []
for l in lines[start:end]:
    m = pat.match(l)
    if not m:
        continue
    addr, mask, val, width, delay, comment = m.groups()
    assert mask.lower() == '0xffff' and width == 'WORD_LEN', l
    entries.append((int(addr, 16), int(val, 16), int(delay), (comment or '').strip()))

out = ['/* SPDX-License-Identifier: GPL-2.0-only */',
       '/*',
       ' * MT9M113 initialisation sequence of the HP TouchPad front camera: PLL, sensor core, ISP, auto exposure/white balance tables.',
       ' * Generated by scripts/tools/gen-mt9m113-table.py from drivers/media/video/msm/mt9m113_reg.c of the CyanogenMod 3.4 tenderloin kernel',
       ' * (Copyright (c) Code Aurora Forum, GPL-2.0). Do not edit by hand.',
       ' */',
       '',
       'struct mt9m113_reg {',
       '\tu16 addr;',
       '\tu16 val;',
       '\tu16 delay_ms;',
       '};',
       '',
       'static const struct mt9m113_reg mt9m113_init_regs[] = {']
for addr, val, delay, comment in entries:
    out.append('\t{ 0x%04x, 0x%04x, %d },%s' % (addr, val, delay, ('\t/* %s */' % comment.replace('*/', '* /')) if comment else ''))
out.append('};')
out.append('')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print('%d entries -> %s' % (len(entries), OUT))
